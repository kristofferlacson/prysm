/**
 * Builds src/features/library/iconData.ts from the Lucide icon set (ISC licence), which is
 * already installed as the interface's own icon library. Each icon's shapes are converted to a
 * single SVG path string so the editor can draw it as one stroked vector path.
 *
 *   node scripts/build-icons.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'node_modules/lucide-react/dist/esm/icons');

const SETS = {
  Arrows: 'arrow-right arrow-left arrow-up arrow-down arrow-up-right arrow-down-right chevron-right chevrons-right corner-down-right move-right refresh-cw undo-2 redo-2 mouse-pointer-2',
  Social: 'heart thumbs-up message-circle message-square share-2 send mail phone at-sign bell user users link rss hash smile',
  Shopping: 'shopping-cart shopping-bag tag tags percent credit-card gift store package truck receipt wallet badge-percent banknote',
  Media: 'music mic headphones play pause camera video film image radio disc-3 volume-2 guitar drum clapperboard tv',
  Nature: 'sun moon cloud cloud-rain snowflake zap flame leaf flower-2 tree-pine mountain waves droplet rainbow sprout wind',
  Travel: 'map-pin map globe compass plane car bike ship house building-2 tent anchor luggage bus',
  Events: 'calendar clock alarm-clock hourglass timer party-popper cake ticket trophy medal crown star sparkles award',
  Food: 'coffee pizza utensils wine beer ice-cream-cone apple cherry cookie croissant cup-soda egg-fried',
  Objects: 'lightbulb rocket key lock search settings smartphone laptop wifi battery book-open pen-tool palette brush scissors paperclip briefcase graduation-cap dumbbell gamepad-2 megaphone glasses umbrella',
  Symbols: 'check x plus minus circle-check circle-alert info circle-help ban eye flag bookmark shield target infinity hand peace quote asterisk',
};

const n = (v) => Number(v);
const f = (v) => +Number(v).toFixed(3);

function toPath([tag, a]) {
  switch (tag) {
    case 'path':
      return a.d;
    case 'circle': {
      const r = n(a.r);
      return `M${f(n(a.cx) - r)} ${f(a.cy)}a${r} ${r} 0 1 0 ${f(r * 2)} 0a${r} ${r} 0 1 0 ${f(-r * 2)} 0`;
    }
    case 'ellipse': {
      const rx = n(a.rx);
      const ry = n(a.ry);
      return `M${f(n(a.cx) - rx)} ${f(a.cy)}a${rx} ${ry} 0 1 0 ${f(rx * 2)} 0a${rx} ${ry} 0 1 0 ${f(-rx * 2)} 0`;
    }
    case 'rect': {
      const x = n(a.x ?? 0);
      const y = n(a.y ?? 0);
      const w = n(a.width);
      const h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx && !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${f(x + rx)} ${y}h${f(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${f(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${f(2 * rx - w)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${f(2 * ry - h)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    case 'line':
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const pts = String(a.points).trim().split(/[\s,]+/).map(Number);
      let d = '';
      for (let i = 0; i < pts.length; i += 2) d += `${i ? 'L' : 'M'}${pts[i]} ${pts[i + 1]}`;
      return d + (tag === 'polygon' ? 'Z' : '');
    }
    default:
      throw new Error(`unsupported element <${tag}>`);
  }
}

const label = (name) => name.replace(/-\d+$/, '').replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const out = [];
const missing = [];
for (const [category, names] of Object.entries(SETS)) {
  for (const name of names.split(' ')) {
    const file = join(iconDir, `${name}.mjs`);
    if (!existsSync(file)) {
      missing.push(name);
      continue;
    }
    // Renamed icons are kept as one-line modules that point at the new name.
    const alias = readFileSync(file, 'utf8').match(/export \{ default \} from '\.\/([^']+)\.mjs'/);
    const mod = await import(pathToFileURL(alias ? join(iconDir, `${alias[1]}.mjs`) : file).href);
    if (!mod.__iconData) {
      missing.push(name);
      continue;
    }
    out.push({ name, label: label(name), category, d: mod.__iconData.node.map(toPath).join('') });
  }
}

const lines = out.map((i) => `  { name: ${JSON.stringify(i.name)}, label: ${JSON.stringify(i.label)}, category: ${JSON.stringify(i.category)}, d: ${JSON.stringify(i.d)} },`);
writeFileSync(
  join(root, 'src/features/library/iconData.ts'),
  `/**
 * Generated by scripts/build-icons.mjs. Do not edit by hand.
 *
 * Line icons from Lucide (https://lucide.dev), ISC License,
 * Copyright (c) Lucide Icons and Contributors. Each icon is one SVG path on a 24 x 24 grid,
 * meant to be stroked with round caps and joins.
 */
export interface IconDef {
  name: string;
  label: string;
  category: string;
  d: string;
}

export const ICON_SIZE = 24;

export const ICONS: IconDef[] = [
${lines.join('\n')}
];
`,
);
console.log(`${out.length} icons written`, missing.length ? `(not in this Lucide version: ${missing.join(', ')})` : '');
